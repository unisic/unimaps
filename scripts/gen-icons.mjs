/**
 * Writes components/icon-paths.ts: the inner SVG of every Phosphor glyph the app uses, bold and fill weights,
 * read from the @phosphor-icons/react defs (React.createElement trees, evaluated here with a string stub).
 * One export per glyph (`XIcon`), so a page bundles only the glyphs it imports.
 * Add a name to NAMES and rerun: node scripts/gen-icons.mjs
 */
import fs from "node:fs";
import path from "node:path";

const NAMES = [
  "ArrowLeft", "ArrowRight", "ArrowUp", "ArrowsClockwise", "ArrowsDownUp", "ArrowsHorizontal", "ArrowsLeftRight",
  "Bell", "Briefcase", "Bug", "Bus", "CalendarBlank", "Cards", "CaretDown", "CaretLeft", "CaretRight", "CaretUp",
  "Check", "Clock", "Crosshair", "DotsThreeVertical", "DownloadSimple", "Drop", "Eye", "EyeSlash", "Flag",
  "FunnelSimpleX", "GpsFix", "GpsSlash", "HandWaving", "House", "Info", "Leaf", "Lightning", "MagnifyingGlass",
  "MapPin", "MapTrifold", "MegaphoneSimple", "Moon", "NavigationArrow", "Path", "PersonSimpleWalk", "RssSimple",
  "ShareNetwork", "ShieldCheck", "SlidersHorizontal", "Snowflake", "Star", "Subway", "Sun", "Ticket", "Tram",
  "WarningCircle", "Wheelchair", "X", "XCircle",
];

const DEFS = "node_modules/@phosphor-icons/react/dist/defs";
const WEIGHTS = ["bold", "fill"];

const attr = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const h = {
  Fragment: null,
  createElement: (tag, props, ...kids) => {
    const inner = kids.join("");
    if (tag === null) return inner;
    const a = Object.entries(props ?? {}).map(([k, v]) => ` ${attr(k)}="${v}"`).join("");
    return inner ? `<${tag}${a}>${inner}</${tag}>` : `<${tag}${a}/>`;
  },
};

const out = [];
for (const name of NAMES) {
  const src = fs.readFileSync(path.join(DEFS, `${name}.es.js`), "utf-8");
  const def = /export\s*\{\s*(\w+) as default\s*\};?\s*$/.exec(src)?.[1];
  const body = src.replace(/^import \* as (\w+) from "react";/m, "const $1 = h;").replace(/export\s*\{[^}]*\};?\s*$/, "");
  const map = new Function("h", `${body}; return ${def};`)(h);
  const w = WEIGHTS.map((k) => {
    if (!map.has(k)) throw new Error(`${name}: no ${k} weight`);
    return `${k}: ${JSON.stringify(map.get(k))}`;
  });
  out.push(`export const ${name}Icon: IconDef = { ${w.join(", ")} };`);
}

fs.writeFileSync(
  "components/icon-paths.ts",
  `/* generated by scripts/gen-icons.mjs from @phosphor-icons/react (MIT): do not edit */\n` +
    `export interface IconDef {\n  bold: string;\n  fill: string;\n}\n\n${out.join("\n")}\n`,
);
console.log(`gen-icons: ${NAMES.length} glyphs`);
